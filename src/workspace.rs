use std::{
    fs,
    io::Write,
    path::{Path, PathBuf},
    process::Stdio,
};

use anyhow::{Context, Result, bail};
use serde::{Deserialize, Serialize};
use tokio::process::Command;

use crate::{
    config::Config, document::statement_markdown, fsutil::atomic_write, language, model::Problem,
};

const META_FILE: &str = ".leetui.toml";

#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct WorkspaceMeta {
    pub slug: String,
    pub question_id: String,
    pub frontend_id: String,
    pub language: String,
    pub solution: PathBuf,
}

#[derive(Debug, Clone)]
pub struct WorkspaceEntry {
    pub directory: PathBuf,
    pub solution: PathBuf,
    pub meta: WorkspaceMeta,
}

/// Opens an existing workspace without changing its language, unless
/// `requested_language` explicitly asks for a switch. New workspaces use the
/// requested language or the configured default.
pub fn prepare(
    config: &Config,
    problem: &Problem,
    requested_language: Option<&str>,
) -> Result<WorkspaceEntry> {
    let id = problem
        .question_frontend_id
        .parse::<u32>()
        .map(|id| format!("{id:04}"))
        .unwrap_or_else(|_| problem.question_frontend_id.clone());
    let directory = config
        .workspace
        .join(format!("{id}-{}", problem.title_slug));
    prepare_in(
        &directory,
        problem,
        requested_language,
        &config.default_language,
    )
}

pub fn prepare_in(
    directory: &Path,
    problem: &Problem,
    requested_language: Option<&str>,
    default_language: &str,
) -> Result<WorkspaceEntry> {
    fs::create_dir_all(directory)?;
    let existing = load_meta(directory)?;
    if let Some(meta) = &existing
        && meta.slug != problem.title_slug
    {
        bail!(
            "workspace {} belongs to `{}`, not `{}`",
            directory.display(),
            meta.slug,
            problem.title_slug
        );
    }
    let requested_language = requested_language.map(language::normalize).transpose()?;
    let existing_language = existing
        .as_ref()
        .map(|meta| language::normalize(&meta.language))
        .transpose()?;
    let language = requested_language
        .or_else(|| existing_language.clone())
        .unwrap_or(language::normalize(default_language)?);
    let snippet = problem
        .code_snippets
        .iter()
        .find(|snippet| snippet.lang_slug == language)
        .with_context(|| {
            let available = problem
                .code_snippets
                .iter()
                .map(|snippet| snippet.lang_slug.as_str())
                .collect::<Vec<_>>()
                .join(", ");
            format!("problem has no `{language}` starter code; available languages: {available}")
        })?;
    let solution_name = solution_name(existing.as_ref(), existing_language.as_deref(), &language);
    let solution = directory.join(&solution_name);
    create_once(&solution, snippet.code.as_bytes())?;

    let statement_path = directory.join("problem.md");
    if !statement_path.exists() {
        let markdown = format!(
            "<!-- Generated by leetui. This file is preserved once created. -->\n\n# {}. {}\n\n**Difficulty:** {}  \n**Topics:** {}\n\n{}",
            problem.question_frontend_id,
            problem.title,
            problem.difficulty,
            problem
                .topic_tags
                .iter()
                .map(|t| t.name.as_str())
                .collect::<Vec<_>>()
                .join(", "),
            statement_markdown(&problem.content)?,
        );
        create_once(&statement_path, markdown.as_bytes())?;
    }

    let meta = WorkspaceMeta {
        slug: problem.title_slug.clone(),
        question_id: problem.question_id.clone(),
        frontend_id: problem.question_frontend_id.clone(),
        language,
        solution: solution_name,
    };
    atomic_write(
        &directory.join(META_FILE),
        toml::to_string_pretty(&meta)?.as_bytes(),
    )?;
    Ok(WorkspaceEntry {
        directory: directory.to_path_buf(),
        solution,
        meta,
    })
}

fn solution_name(
    existing: Option<&WorkspaceMeta>,
    existing_language: Option<&str>,
    language: &str,
) -> PathBuf {
    if let (Some(meta), Some(existing_language)) = (existing, existing_language)
        && existing_language == language
    {
        return meta.solution.clone();
    }

    let suffix = extension(language);
    if existing_language.is_some_and(|existing| extension(existing) == suffix) {
        // Some distinct LeetCode languages share a file extension, notably
        // python/python3 and the SQL dialects. A language switch must not
        // silently reuse source written for the previous language.
        PathBuf::from(format!("solution.{language}.{suffix}"))
    } else {
        PathBuf::from(format!("solution.{suffix}"))
    }
}

fn create_once(path: &Path, bytes: &[u8]) -> Result<()> {
    match fs::OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(path)
    {
        Ok(mut file) => {
            file.write_all(bytes)?;
            file.flush()?;
            Ok(())
        }
        Err(error) if error.kind() == std::io::ErrorKind::AlreadyExists => Ok(()),
        Err(error) => Err(error.into()),
    }
}

fn load_meta(directory: &Path) -> Result<Option<WorkspaceMeta>> {
    let path = directory.join(META_FILE);
    if !path.exists() {
        return Ok(None);
    }
    let mut meta: WorkspaceMeta = toml::from_str(&fs::read_to_string(&path)?)
        .with_context(|| format!("invalid workspace metadata in {}", path.display()))?;
    meta.language = language::normalize(&meta.language)?;
    crate::cache::validate_slug(&meta.slug)?;
    validate_solution_path(&meta.solution)?;
    Ok(Some(meta))
}

fn validate_solution_path(path: &Path) -> Result<()> {
    let mut components = path.components();
    let is_filename = matches!(components.next(), Some(std::path::Component::Normal(_)))
        && components.next().is_none();
    if !is_filename {
        bail!(
            "workspace solution path must be a file name, not {}",
            path.display()
        );
    }
    Ok(())
}

pub fn from_path(path: &Path) -> Result<WorkspaceEntry> {
    let path = path
        .canonicalize()
        .with_context(|| format!("{} does not exist", path.display()))?;
    let directory = if path.is_dir() {
        path.clone()
    } else {
        path.parent()
            .context("solution path has no parent")?
            .to_path_buf()
    };
    let meta_path = directory.join(META_FILE);
    if !meta_path.exists() {
        bail!(
            "{} has no {META_FILE}; use `leetui pick` first",
            directory.display()
        );
    }
    let mut meta: WorkspaceMeta = toml::from_str(&fs::read_to_string(&meta_path)?)?;
    meta.language = language::normalize(&meta.language)?;
    crate::cache::validate_slug(&meta.slug)?;
    validate_solution_path(&meta.solution)?;
    let solution = if path.is_file() {
        if path.file_name() != meta.solution.file_name() {
            bail!(
                "{} is not the workspace solution {}; open the workspace directory instead",
                path.display(),
                meta.solution.display()
            );
        }
        path
    } else {
        directory.join(&meta.solution)
    };
    Ok(WorkspaceEntry {
        directory,
        solution,
        meta,
    })
}

pub async fn open_editor(config: &Config, entry: &WorkspaceEntry) -> Result<()> {
    let command = config.editor_command()?;
    let mut args = Vec::new();
    let mut has_placeholder = false;
    for arg in command.iter().skip(1) {
        if arg.contains("{file}") || arg.contains("{dir}") {
            has_placeholder = true;
        }
        args.push(
            arg.replace("{file}", &entry.solution.to_string_lossy())
                .replace("{dir}", &entry.directory.to_string_lossy()),
        );
    }
    if !has_placeholder {
        args.push(entry.solution.to_string_lossy().into_owned());
    }
    let status = Command::new(&command[0])
        .args(args)
        .stdin(Stdio::inherit())
        .stdout(Stdio::inherit())
        .stderr(Stdio::inherit())
        .status()
        .await?;
    if !status.success() {
        bail!("editor exited with {status}");
    }
    Ok(())
}

pub fn extension(language: &str) -> &str {
    match language {
        "cpp" => "cpp",
        "java" => "java",
        "python3" | "python" => "py",
        "javascript" => "js",
        "typescript" => "ts",
        "csharp" => "cs",
        "c" => "c",
        "golang" => "go",
        "kotlin" => "kt",
        "swift" => "swift",
        "rust" => "rs",
        "ruby" => "rb",
        "php" => "php",
        "dart" => "dart",
        "scala" => "scala",
        "elixir" => "ex",
        "erlang" => "erl",
        "racket" => "rkt",
        "mysql" | "mssql" | "oraclesql" => "sql",
        other => other,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn maps_leetcode_language_slugs() {
        assert_eq!(extension("rust"), "rs");
        assert_eq!(extension("golang"), "go");
        assert_eq!(extension("python3"), "py");
        assert_eq!(extension("custom"), "custom");
    }

    #[test]
    fn common_alias_selects_canonical_starter_code() {
        let directory = tempfile::tempdir().unwrap();
        let mut problem = problem();
        problem.code_snippets.push(crate::model::CodeSnippet {
            lang: "C++".into(),
            lang_slug: "cpp".into(),
            code: "cpp starter".into(),
        });
        let config = Config {
            default_language: "c++".into(),
            editor: Vec::new(),
            workspace: directory.path().into(),
        };
        let entry = prepare(&config, &problem, None).unwrap();
        assert_eq!(entry.meta.language, "cpp");
        assert_eq!(entry.solution.file_name().unwrap(), "solution.cpp");
    }

    fn problem() -> Problem {
        Problem {
            question_id: "1".into(),
            question_frontend_id: "1".into(),
            title: "Two Sum".into(),
            title_slug: "two-sum".into(),
            content: "<p>Statement</p>".into(),
            difficulty: "Easy".into(),
            is_paid_only: false,
            status: None,
            sample_test_case: "[]".into(),
            example_testcases: None,
            meta_data: "{}".into(),
            code_snippets: vec![
                crate::model::CodeSnippet {
                    lang: "Rust".into(),
                    lang_slug: "rust".into(),
                    code: "rust starter".into(),
                },
                crate::model::CodeSnippet {
                    lang: "Python3".into(),
                    lang_slug: "python3".into(),
                    code: "python starter".into(),
                },
            ],
            topic_tags: Vec::new(),
            hints: Vec::new(),
            stats: None,
            solution: None,
        }
    }

    #[test]
    fn reopening_preserves_language_and_user_files() {
        let directory = tempfile::tempdir().unwrap();
        let config = Config {
            default_language: "rust".into(),
            editor: Vec::new(),
            workspace: directory.path().into(),
        };
        let problem = problem();
        let python = prepare(&config, &problem, Some("python3")).unwrap();
        fs::write(python.directory.join("problem.md"), "my notes").unwrap();

        let reopened = prepare(&config, &problem, None).unwrap();
        assert_eq!(reopened.meta.language, "python3");
        assert_eq!(reopened.solution, python.solution);
        assert_eq!(
            fs::read_to_string(reopened.directory.join("problem.md")).unwrap(),
            "my notes"
        );
    }

    #[test]
    fn explicit_language_switch_is_deliberate() {
        let directory = tempfile::tempdir().unwrap();
        let config = Config {
            default_language: "rust".into(),
            editor: Vec::new(),
            workspace: directory.path().into(),
        };
        let problem = problem();
        prepare(&config, &problem, Some("python3")).unwrap();
        let switched = prepare(&config, &problem, Some("rust")).unwrap();
        assert_eq!(switched.meta.language, "rust");
        assert_eq!(switched.solution.file_name().unwrap(), "solution.rs");
        assert_eq!(
            fs::read_to_string(switched.solution).unwrap(),
            "rust starter"
        );
    }

    #[test]
    fn same_extension_language_switch_uses_distinct_files() {
        let directory = tempfile::tempdir().unwrap();
        let config = Config {
            default_language: "python3".into(),
            editor: Vec::new(),
            workspace: directory.path().into(),
        };
        let mut problem = problem();
        problem.code_snippets.push(crate::model::CodeSnippet {
            lang: "Python".into(),
            lang_slug: "python".into(),
            code: "python starter".into(),
        });

        let original = prepare(&config, &problem, Some("python3")).unwrap();
        fs::write(&original.solution, "user python3 code").unwrap();

        let switched = prepare(&config, &problem, Some("python")).unwrap();
        assert_eq!(original.solution.file_name().unwrap(), "solution.py");
        assert_eq!(switched.solution.file_name().unwrap(), "solution.python.py");
        assert_eq!(
            fs::read_to_string(&original.solution).unwrap(),
            "user python3 code"
        );
        assert_eq!(
            fs::read_to_string(&switched.solution).unwrap(),
            "python starter"
        );

        fs::write(&switched.solution, "user python code").unwrap();
        let reopened = prepare(&config, &problem, None).unwrap();
        assert_eq!(reopened.solution, switched.solution);
        assert_eq!(
            fs::read_to_string(&reopened.solution).unwrap(),
            "user python code"
        );
    }

    #[test]
    fn rejects_non_solution_files_as_workspace_targets() {
        let directory = tempfile::tempdir().unwrap();
        let config = Config {
            default_language: "rust".into(),
            editor: Vec::new(),
            workspace: directory.path().into(),
        };
        let entry = prepare(&config, &problem(), None).unwrap();
        assert!(from_path(&entry.directory.join("problem.md")).is_err());
        assert!(from_path(&entry.solution).is_ok());
    }
}
